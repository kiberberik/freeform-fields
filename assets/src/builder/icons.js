	buttons,
	calendar,
	check,
	classic,
	color,
	connection,
	copy,
	customLink,
	details,
	envelope,
	file,
	formSelect,
	formatListBullets,
	gallery,
	group,
	image,
	info,
	layout,
	link,
	lock,
	mapMarker,
